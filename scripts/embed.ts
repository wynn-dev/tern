// Generates src/server/assets.gen.ts, which imports every built web file so
// `bun build --compile` embeds the UI in the single tern binary.
import { Glob } from "bun";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "../dist/web");
const files = [...new Glob("**/*").scanSync({ cwd: root })].sort();
if (!files.length) throw new Error("dist/web is empty: run `bun run build:web` first");

const lines = files.map((f, i) => `import f${i} from "../../dist/web/${f}" with { type: "file" };`);
const map = files.map((f, i) => `  ${JSON.stringify("/" + f)}: f${i},`);
await Bun.write(
  resolve(import.meta.dir, "../src/server/assets.gen.ts"),
  `// generated by scripts/embed.ts\n// @ts-nocheck\n${lines.join("\n")}\n\nexport const assets: Record<string, string> = {\n${map.join("\n")}\n};\n`,
);
console.log(`embedded ${files.length} files`);
